// Renders SVG slices and README.md from data/ + content.ts.
//   node src/render.ts [--theme ice|amber|neon] [--root <dir>]
import {mkdir, readFile, rm, writeFile} from 'node:fs/promises';
import {parseArgs} from 'node:util';
import {THEMES, esc} from './console.ts';
import {LOGIN, SITE_URL} from './content.ts';
import {type Calendar} from './data.ts';
import {city, cityAlt, phoneCity} from './sections/city.ts';
import {
	LINKS,
	about,
	button,
	footer,
	header,
	headerAlt,
	phoneAbout,
	phoneButton,
	phoneFooter,
	phoneHeader,
	phoneSectionHead,
	phoneStack,
	sectionHead,
	stack,
} from './sections/frame.ts';
import {CREDIT_POST, CREDIT_URL} from './shared.ts';

const DEFAULT_THEME = 'ice';
const RAW = `https://github.com/${LOGIN}/${LOGIN}/raw/main/assets`;
const PHONE_QUERY = '(max-width: 600px)';
const ABOUT_ALT =
	'David Miller: backend engineer at CoreWeave — Go and Kubernetes for AI infrastructure billing. Former AWS boto3 maintainer, ex-NYT. Queens, NY.';
const STACK_ALT =
	'Stack: Go, Kubernetes, Postgres, Kafka, Redis, gRPC/Connect, Prometheus, Grafana, CI/CD; also Python and Java.';

class Page {
	files = new Map<string, string>();
	rows: string[][] = [];

	add(
		file: string,
		[desktop, phone]: [string, string],
		width: string,
		alt: string,
		href?: string,
		sameRow = false,
	): void {
		this.files.set(file, desktop);
		this.files.set(`phone/${file}`, phone);
		const text = esc(alt.replace(/\s+/g, ' ').trim());
		const img = `<picture><source media="${PHONE_QUERY}" srcset="${RAW}/phone/${file}"><img src="./assets/${file}" width="${width}" align="top" alt="${text}"></picture>`;
		const html = href ? `<a href="${esc(href)}">${img}</a>` : img;
		if (sameRow && this.rows.length) this.rows.at(-1)!.push(html);
		else this.rows.push([html]);
	}

	readme(): string {
		return `<!-- Generated by \`mise run readme\` from src/. Edit that, not this. -->
<p align="center">
${this.rows.map(r => r.join('')).join('\n')}
</p>

<p align="center"><sub>Regenerated by <code>mise run readme</code> · site: <a href="${SITE_URL}">${SITE_URL.replace('https://', '')}</a> · console design and contribution city by <a href="${CREDIT_URL}">Giorgi Kobaidze</a> (<a href="${CREDIT_POST}">how he built it</a>), MIT.</sub></p>
`;
	}
}

async function main() {
	const {values} = parseArgs({
		options: {theme: {type: 'string', default: DEFAULT_THEME}, root: {type: 'string', default: '.'}},
	});
	const t = THEMES[values.theme!];
	if (!t) throw new Error(`unknown theme ${values.theme}`);
	const root = values.root!;

	const calendar: Calendar | null = JSON.parse(await readFile('data/calendar.json', 'utf8').catch(() => 'null'));
	const updated = calendar?.at(-1)?.[0] ?? '';
	let n = 0;
	const counter = () => `// ${String(++n).padStart(2, '0')}`;
	const both = (a: Promise<string>, b: Promise<string>) => Promise.all([a, b]);

	const page = new Page();
	const [headerTop, headerTail] = await header(t);
	const [phoneTop, phoneTail] = await phoneHeader(t);
	page.add('header.svg', [headerTop, phoneTop], '100%', headerAlt());
	page.add(
		'header-employer.svg',
		[headerTail, phoneTail],
		'100%',
		'Building the billing platform at CoreWeave',
		'https://www.coreweave.com',
	);

	{
		const c = counter();
		page.add('about.svg', await both(about(t, c), phoneAbout(t, c)), '100%', ABOUT_ALT);
	}
	{
		const c = counter();
		page.add('stack.svg', await both(stack(t, c), phoneStack(t, c)), '100%', STACK_ALT);
	}

	{
		const c = counter();
		page.add(
			'links.svg',
			await both(
				sectionHead(t, 'connect', c, 'open --url site linkedin github'),
				phoneSectionHead(t, 'connect', c, 'open --url …'),
			),
			'100%',
			'Connect',
		);
	}
	for (const [k, b] of LINKS.entries()) {
		page.add(
			`links/${k + 1}.svg`,
			await both(button(t, b, k, LINKS.length), phoneButton(t, b, k, LINKS.length)),
			`${100 / LINKS.length}%`,
			b.label,
			b.url,
			k > 0,
		);
	}

	if (calendar) {
		const c = counter();
		page.add(
			'contribution-city.svg',
			await both(city(t, calendar, updated, c), phoneCity(t, calendar, updated, c)),
			'100%',
			cityAlt(calendar),
		);
	}

	page.add('footer.svg', await both(footer(t), phoneFooter(t)), '100%', 'Connection closed.', CREDIT_URL);

	await rm(`${root}/assets`, {recursive: true, force: true});
	for (const [name, content] of page.files) {
		const path = `${root}/assets/${name}`;
		await mkdir(path.slice(0, path.lastIndexOf('/')), {recursive: true});
		await writeFile(path, content);
	}
	await writeFile(`${root}/README.md`, page.readme());
	console.log(`rendered ${page.files.size} SVGs (${t.name}) and README.md into ${root}`);
}

await main();
